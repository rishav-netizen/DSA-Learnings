#include <iostream>
#include <cmath>

using namespace std;

int main(void)
{
    cout << sqrt(36) << endl;
    cout << pow(2, 3) << endl;
    cout << round(4.4) << endl;
    cout << ceil(3.1) << endl;
    cout << floor(4.9) << endl;
    cout << fmax(4, 9) << endl;
    cout << fmin(4, 9) << endl;

    return 0;
}